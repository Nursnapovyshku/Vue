import { test, expect } from '@playwright/test'

test('tasks can be added, edited, filtered, completed, saved and deleted', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('No tasks yet.', { exact: true })).toBeVisible()
  const form = page.locator('.task-form')
  const filters = page.locator('.filters')
  await form.getByLabel('Title', { exact: true }).fill('   ')
  await form.getByRole('button', { name: 'Add task' }).click()
  await expect(page.getByRole('alert')).toHaveText('Enter a task title.')
  await form.getByLabel('Title', { exact: true }).fill('Read a book')
  await form.getByLabel('Description').fill('Read chapter one')
  await form.getByLabel('Priority').selectOption('High')
  await form.getByRole('button', { name: 'Add task' }).click()
  await form.getByLabel('Title', { exact: true }).fill('Buy groceries')
  await form.getByLabel('Priority').selectOption('Low')
  await form.getByRole('button', { name: 'Add task' }).click()
  await expect(page.locator('.task-item')).toHaveCount(2)
  await expect(page.locator('.stat-card strong')).toHaveText(['2', '2', '0'])
  await filters.getByLabel('Search').fill('READ')
  await expect(page.locator('.task-item')).toHaveCount(1)
  await filters.getByLabel('Priority').selectOption('Low')
  await expect(page.getByText('No matching tasks.', { exact: true })).toBeVisible()
  await filters.getByLabel('Priority').selectOption('all')
  await filters.getByLabel('Search').fill('')
  const book = page.locator('.task-item').filter({ has: page.getByRole('heading', { name: 'Read a book', exact: true }) })
  await book.getByRole('button', { name: 'Edit Read a book', exact: true }).click()
  await book.getByRole('button', { name: 'Complete', exact: true }).click()
  await form.getByLabel('Title', { exact: true }).fill('Read two chapters')
  await form.getByRole('button', { name: 'Save changes' }).click()
  await expect(page.locator('.stat-card strong')).toHaveText(['2', '1', '1'])
  await filters.getByLabel('Status').selectOption('completed')
  await expect(page.locator('.task-item')).toHaveCount(1)
  await expect(page.getByRole('heading', { name: 'Read two chapters' })).toBeVisible()
  await page.locator('.task-item').getByLabel('Priority').selectOption('Medium')
  await page.reload()
  await expect(page.locator('.task-item')).toHaveCount(2)
  const renamed = page.locator('.task-item').filter({ has: page.getByRole('heading', { name: 'Read two chapters', exact: true }) })
  await expect(renamed.getByLabel('Priority')).toHaveValue('Medium')
  await renamed.getByRole('button', { name: 'Edit Read two chapters', exact: true }).click()
  await form.getByLabel('Title', { exact: true }).fill('Unsaved title')
  await form.getByRole('button', { name: 'Cancel' }).click()
  await expect(page.getByRole('heading', { name: 'Read two chapters' })).toBeVisible()
  await renamed.getByRole('button', { name: 'Activate', exact: true }).click()
  await expect(page.locator('.stat-card strong')).toHaveText(['2', '2', '0'])
  await renamed.getByRole('button', { name: 'Delete Read two chapters', exact: true }).click()
  await page.getByRole('button', { name: 'Delete Buy groceries', exact: true }).click()
  await page.reload()
  await expect(page.getByText('No tasks yet.', { exact: true })).toBeVisible()
})

test('invalid stored tasks do not crash the app', async ({ page }) => {
  await page.addInitScript(() => localStorage.setItem('sis2-vue-tasks', '{broken'))
  await page.goto('/')
  await expect(page.getByText('Saved tasks could not be loaded', { exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Add task' })).toBeVisible()
})

test('desktop and mobile render without horizontal overflow', async ({ page }) => {
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  await page.goto('/')
  await page.locator('.task-form').getByLabel('Title', { exact: true }).fill('LongTitle'.repeat(13))
  await page.getByRole('button', { name: 'Add task' }).click()
  for (const width of [1280, 900, 375, 320]) {
    await page.setViewportSize({ width, height: 900 })
    await expect(page.getByRole('heading', { name: 'Task Manager', exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: `test-results/tasks-${width}.png`, fullPage: true })
  }
  expect(errors).toEqual([])
})
